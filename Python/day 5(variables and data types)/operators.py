#Arithmetic operators
a=23
b=45
print(a+b) #add 
print(a-b) #subtract
print(a*b) #multiply
print(a/b) #divide

#Assignment operators
c=34-4
d=4
print(c) #assigned 34-4 in c
# d+=3 increments d by 3 and assigns it to d
# d-=3 decrements d by 3 and assigns it to d
# d*=3 multiplies d by 3 and assigns it to d
# d/=2 divides d by 3 and assigns it to d
print(d)

